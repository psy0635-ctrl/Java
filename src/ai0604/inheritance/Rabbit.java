package ai0604.inheritance;

/*
 * =============================================
 * [부모 클래스] Rabbit (토끼)
 * =============================================
 * 모든 토끼가 공통으로 갖는 속성과 기능을 정의한 설계도.
 * HouseRabbit(집토끼), MountainRabbit(산토끼)이 이 클래스를 상속받아 사용한다.
 *
 * [상속이란?]
 * 부모 클래스의 필드(변수)와 메서드(기능)를 자식 클래스가 물려받는 것.
 * 자식 클래스는 부모의 것을 그대로 쓰면서, 자신만의 기능을 추가할 수 있다.
 * =============================================
 */
public class Rabbit {
// super 클래스의 필드 또는 메소드 앞에 private를 붙히면 sub 클래스의 사용이 제한된다.
    // -----------------------------------------------
    // [필드] 모든 토끼가 공통으로 가지는 속성(변수)
    // -----------------------------------------------
    String shape;   // 토끼의 모양 (예: "동그라미", "세모")
    int xPos;       // 토끼의 x좌표 (가로 위치, 기본값 0)
    int yPos;       // 토끼의 y좌표 (세로 위치, 기본값 0)


    // -----------------------------------------------
    // [생성자] 객체를 만들 때 자동으로 호출되는 특별한 메서드
    // 생성자 이름은 반드시 클래스 이름과 같아야 한다.
    // -----------------------------------------------

    // 기본 생성자: 아무 값 없이 객체만 만들 때 사용
    // 예) Rabbit r = new Rabbit();
    public Rabbit() {
        // 비어있음 → 모든 필드는 Java 기본값(int=0, String=null)으로 초기화됨
    }

    // 매개변수 생성자: shape 값을 받아서 객체를 만들 때 사용
    // 예) Rabbit r = new Rabbit("동그라미");
    // this.shape → 이 객체의 shape 필드를 의미
    // shape     → 매개변수로 전달받은 값
    public Rabbit(String shape) {
        this.shape = shape; // 전달받은 shape 값을 이 객체의 shape 필드에 저장
    }


    // -----------------------------------------------
    // [메서드] 모든 토끼가 공통으로 할 수 있는 기능
    // -----------------------------------------------

    // 토끼의 위치를 지정한 x, y 좌표로 설정하는 메서드
    // 예) setLocation(30, 50) → xPos=30, yPos=50
    public void setLocation(int x, int y) {
        this.xPos = x; // x 매개변수 값을 xPos 필드에 저장
        this.yPos = y; // y 매개변수 값을 yPos 필드에 저장
    }

    // 토끼를 오른쪽으로 10칸 이동시키는 메서드
    // += 는 기존 값에 10을 더하는 연산자
    // 예) xPos가 30이었다면 → 30 + 10 = 40
    public void MoveRightTen() {
        this.xPos += 10;
    }

    // 토끼를 왼쪽으로 10칸 이동시키는 메서드
    // -= 는 기존 값에서 10을 빼는 연산자
    // 예) xPos가 0이었다면 → 0 - 10 = -10, 한 번 더 호출하면 → -20
    public void moveLeftTen() {
        this.xPos -= 10;
    }

    // 토끼의 현재 모양과 위치 정보를 출력하는 메서드
    // 예) 동그라미 모양의 토끼는 (40, 50) 좌표에 위치하고 있다.
    public void printInfo() {
        System.out.println(shape + " 모양의 토끼는 (" + xPos + ", " + yPos + ") 좌표에 위치하고 있다.");
    }
}
