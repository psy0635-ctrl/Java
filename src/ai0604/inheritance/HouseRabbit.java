package ai0604.inheritance;

/*
 * =============================================
 * [자식 클래스] HouseRabbit (집토끼)
 * =============================================
 * Rabbit을 상속받은 집토끼 클래스.
 * "extends Rabbit" → Rabbit의 모든 필드와 메서드를 물려받는다.
 *
 * [물려받는 것들]
 *   - 필드: shape, xPos, yPos
 *   - 메서드: setLocation(), MoveRightTen(), moveLeftTen(), printInfo()
 *
 * [추가하는 것들]
 *   - 필드: masterName (집토끼만 갖는 주인 이름)
 *   - 메서드: eatFeed() (집토끼만 하는 사료 먹기)
 * =============================================
 */
public class HouseRabbit extends Rabbit {

    // -----------------------------------------------
    // [추가 필드] 집토끼만 갖는 고유 속성
    // -----------------------------------------------
    String masterName; // 집토끼를 키우는 주인의 이름 (예: "폴리")


    // -----------------------------------------------
    // [추가 메서드] 집토끼만 할 수 있는 기능
    // -----------------------------------------------

    // 주인이 주는 사료를 먹는 메서드
    // feedName: 사료의 종류를 매개변수로 전달받음 (예: "아주 좋은")
    // masterName: 이 객체의 masterName 필드 값을 사용
    // 예) 집토끼가 폴리 주인이 주는 아주 좋은 사료를 먹는다.
    public void eatFeed(String feedName) {
        System.out.println("집토끼가 " + masterName + " 주인이 주는 " + feedName + " 사료를 먹는다.");
    }
}
