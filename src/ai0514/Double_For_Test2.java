package ai0514;

public class Double_For_Test2 {
    public static void main(String[] args) {
        for (int i = 1; i <=9; i++) {
            for (int j = 2; j <=9 ; j++) {
                System.out.printf("%d * %d = %d\t", i, j, i * j);
            }
            System.out.println();
        }

    }

}

